#!/usr/bin/env node
/**
 * merge-b2b-contacts.cjs — unify b2b-enriched.json (MQ/GP) + b2b-us-enriched.json (US regions)
 * into a single contact source for b2b-cold-outreach.cjs.
 *
 * Usage:
 *   node scripts/automation/merge-b2b-contacts.cjs           # dry-run: counts
 *   node scripts/automation/merge-b2b-contacts.cjs --send    # write unified file
 *   node scripts/automation/merge-b2b-contacts.cjs --out <path>  # custom output path
 *
 * Output: scripts/automation/data/b2b-contacts-unified.json
 *   Same schema as b2b-enriched.json: { _note, updatedAt, count, contacts: [...] }
 *   Each contact has { email, name, town, island, fit, hook, url, source }
 *   US contacts also carry { beach, stars, enrichedAt } extras for auditing.
 *
 * Integration with b2b-cold-outreach.cjs:
 *   Change SRC_PATH in outreach from data/b2b-enriched.json to data/b2b-contacts-unified.json
 *   — or symlink. The unified file uses the SAME contact fields.
 */
const fs = require('fs')
const path = require('path')
const { createHash } = require('crypto')

const DATA_DIR = path.join(__dirname, 'data')
const MQ_PATH = path.join(DATA_DIR, 'b2b-enriched.json')
const US_PATH = path.join(DATA_DIR, 'b2b-us-enriched.json')
const DEFAULT_OUT = path.join(DATA_DIR, 'b2b-contacts-unified.json')

function emailHash(e) { return createHash('sha256').update(String(e).trim().toLowerCase()).digest('hex').slice(0, 32) }
function loadJSON(p, fb) { try { return JSON.parse(fs.readFileSync(p, 'utf8')) } catch { console.error(`  ! Cannot read ${p}`); return fb } }

function main() {
  const SEND = process.argv.includes('--send')
  const outIdx = process.argv.indexOf('--out')
  const OUT_PATH = outIdx >= 0 ? process.argv[outIdx + 1] || DEFAULT_OUT : DEFAULT_OUT

  console.log('=== merge-b2b-contacts — unify MQ/GP + US ===')

  const mq = loadJSON(MQ_PATH, { contacts: [] })
  const us = loadJSON(US_PATH, { contacts: [] })

  const mqContacts = (mq.contacts || []).map(c => ({ ...c, _sourceFile: 'b2b-enriched.json' }))
  const usContacts = (us.contacts || []).map(c => ({ ...c, _sourceFile: 'b2b-us-enriched.json' }))

  // Dedup by email hash across both sources
  const seen = new Set()
  const merged = []

  for (const c of [...mqContacts, ...usContacts]) {
    const key = emailHash(c.email || '')
    if (seen.has(key)) continue
    seen.add(key)
    // Remove internal tracking field
    const { _sourceFile, ...contact } = c
    merged.push(contact)
  }

  const enrichedAt = new Date().toISOString()

  // Stats by island/region
  const byIsland = {}
  merged.forEach(c => { const i = c.island || 'unknown'; byIsland[i] = (byIsland[i] || 0) + 1 })

  if (SEND) {
    fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true })
    fs.writeFileSync(OUT_PATH, JSON.stringify({
      _note: `Unified B2B contacts: b2b-enriched.json (MQ/GP) + b2b-us-enriched.json (US). Generated by merge-b2b-contacts.cjs.`,
      updatedAt: enrichedAt,
      count: merged.length,
      contacts: merged,
    }, null, 2))
    console.log(`\nWritten: ${OUT_PATH}`)
  } else {
    console.log(`\nDry-run (use --send to write to ${OUT_PATH}):`)
  }
  console.log(`  MQ/GP contacts: ${mqContacts.length}`)
  console.log(`  US contacts: ${usContacts.length}`)
  console.log(`  Duplicates removed: ${mqContacts.length + usContacts.length - merged.length}`)
  console.log(`  Total unified: ${merged.length}`)
  Object.entries(byIsland).sort().forEach(([i, n]) => console.log(`  ${i}: ${n}`))
  console.log(`\nTo use with b2b-cold-outreach.cjs:`)
  console.log(`  Point SRC_PATH to ${OUT_PATH} instead of data/b2b-enriched.json`)
  console.log(`  (All contacts share the same email/name/town/island/fit/hook/url fields)`)
}

main()
