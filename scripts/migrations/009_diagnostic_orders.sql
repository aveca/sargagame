-- Appliquer en production UNIQUEMENT après autorisation humaine (fondateur).
-- Ce fichier ne modifie aucune donnée : il prépare le schéma cible.
-- Idempotent : CREATE TABLE IF NOT EXISTS, relançable sans effet de bord.

CREATE TABLE IF NOT EXISTS public.diagnostic_orders (
  id                  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  beach_slug          text        NOT NULL,
  region              text        NOT NULL,
  customer_email      text        NOT NULL,
  amount_cents        integer     NOT NULL DEFAULT 4900,
  currency            text        NOT NULL DEFAULT 'EUR',
  status              text        NOT NULL DEFAULT 'pending',
  mollie_payment_id   text,
  mollie_checkout_id  text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_diagnostic_orders_status
  ON public.diagnostic_orders (status);
CREATE INDEX IF NOT EXISTS idx_diagnostic_orders_mollie_payment_id
  ON public.diagnostic_orders (mollie_payment_id);
CREATE INDEX IF NOT EXISTS idx_diagnostic_orders_beach_created
  ON public.diagnostic_orders (beach_slug, created_at DESC);

