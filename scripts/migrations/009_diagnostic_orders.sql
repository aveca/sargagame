-- Diagnostic Express 49 € — tables des commandes de diagnostic et des livraisons
-- Appliquer en production UNIQUEMENT après autorisation humaine (fondateur).
-- Ce fichier ne modifie aucune donnée : il prépare le schéma cible.
-- Idempotent : CREATE TABLE IF NOT EXISTS, relançable sans effet de bord.
--
-- Conformité avec le code :
--   scripts/diagnostic/create-checkout.mjs  (insert: payment_id, product, status,
--       client_email, client_name, contact_name, establishment, sector, island,
--       amount, currency, mollie_mode, mollie_checkout_url, metadata)
--   scripts/diagnostic/lib/fulfillment.mjs  (update/select: order_id, payment_id,
--       status, updated_at, ready_at, document_path, document_sha256,
--       observation_ts, observation_source, data_age_minutes, error, delivered_at)
--   scripts/diagnostic/lib/order-state.mjs  (validateOrderRow: payment_id,
--       client_email, currency, amount, establishment, sector, status)
--   workers/sg-payments/index.js            (select: order_id, payment_id, product,
--       status, client_email, client_name, contact_name, establishment, sector,
--       island, amount, currency, paid_at, created_at)

CREATE TABLE IF NOT EXISTS public.diagnostic_orders (
  order_id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id          text        NOT NULL UNIQUE,
  product             text        NOT NULL DEFAULT 'diagnostic_express',
  status              text        NOT NULL DEFAULT 'pending_payment',
  client_email        text        NOT NULL,
  client_name         text,
  contact_name        text,
  establishment       text        NOT NULL,
  sector              text        NOT NULL,
  island              text        NOT NULL DEFAULT 'Martinique',
  amount              integer     NOT NULL DEFAULT 4900,
  currency            text        NOT NULL DEFAULT 'EUR',
  mollie_mode         text,
  mollie_checkout_url text,
  metadata            jsonb,
  paid_at             timestamptz,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  ready_at            timestamptz,
  document_path       text,
  document_sha256     text,
  observation_ts      timestamptz,
  observation_source  text,
  data_age_minutes    integer,
  error               text,
  delivered_at        timestamptz,

  CONSTRAINT diagnostic_orders_amount_check
    CHECK (amount = 4900),
  CONSTRAINT diagnostic_orders_currency_check
    CHECK (currency = 'EUR')
);

CREATE INDEX IF NOT EXISTS idx_diagnostic_orders_status
  ON public.diagnostic_orders (status);
CREATE INDEX IF NOT EXISTS idx_diagnostic_orders_payment_id
  ON public.diagnostic_orders (payment_id);
CREATE INDEX IF NOT EXISTS idx_diagnostic_orders_client_email
  ON public.diagnostic_orders (client_email);
CREATE INDEX IF NOT EXISTS idx_diagnostic_orders_product_status
  ON public.diagnostic_orders (product, status);

-- Table de traçage des livraisons (référencée par fulfillment.mjs)
CREATE TABLE IF NOT EXISTS public.diagnostic_deliveries (
  id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id          bigint      REFERENCES public.diagnostic_orders(order_id),
  payment_id        text        NOT NULL,
  channel           text        NOT NULL DEFAULT 'email',
  recipient         text        NOT NULL,
  subject           text,
  document_path     text,
  document_sha256   text,
  status            text        NOT NULL DEFAULT 'pending',
  metadata          jsonb,
  created_at        timestamptz NOT NULL DEFAULT now(),
  error             text,
  provider          text
);

CREATE INDEX IF NOT EXISTS idx_diagnostic_deliveries_payment_id
  ON public.diagnostic_deliveries (payment_id);
CREATE INDEX IF NOT EXISTS idx_diagnostic_deliveries_status
  ON public.diagnostic_deliveries (status);
CREATE INDEX IF NOT EXISTS idx_diagnostic_deliveries_order_id
  ON public.diagnostic_deliveries (order_id);

-- RLS : service_role uniquement
REVOKE ALL ON TABLE public.diagnostic_orders FROM PUBLIC;
REVOKE ALL ON TABLE public.diagnostic_orders FROM anon;
REVOKE ALL ON TABLE public.diagnostic_orders FROM authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.diagnostic_orders TO service_role;

REVOKE ALL ON TABLE public.diagnostic_deliveries FROM PUBLIC;
REVOKE ALL ON TABLE public.diagnostic_deliveries FROM anon;
REVOKE ALL ON TABLE public.diagnostic_deliveries FROM authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.diagnostic_deliveries TO service_role;
